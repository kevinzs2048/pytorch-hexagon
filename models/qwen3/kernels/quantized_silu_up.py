# Experimental SiLU × dequantized up for the symmetric row quantizer.
# Contract: batch=1, rows=4..32, width=3072; contiguous G/U/S/Y, W[3072].
# G/S/W/Y are FP32, U is INT32. Up order: (S * float(U)) * W.
# The FP32 output is approximate; only the specified row quantizer may consume it.
# It must not replace an ordinary SiLU or a general FP32 multiplication.
# Strict whole-row fallback and scale/rounding-boundary repair are retained.
# Numerical derivation and final model acceptance are separate from object build.
import triton
import triton.language as tl
from models.qwen3.kernels.strict_decode import _exp_compat
@triton.jit
def _exp_guarded_domain(d):
    # Caller supplies d in [-16,16], including replacement zero for rejected lanes.
    bounded = d
    t = bounded * 1.4426950408889634
    biased = t + 12582912.0
    qfloat = biased - 12582912.0
    q = biased.to(tl.int32, bitcast=True) - 1262485504
    s = qfloat * -0.693145751953125 + bounded
    s = qfloat * -1.428606765330187e-06 + s
    u = 0.00019852761761285365 * s + 0.0013930435525253415
    u = u * s + 0.008333360776305199
    u = u * s + 0.041666485369205475
    u = u * s + 0.1666666716337204
    u = u * s + 0.5
    u = 1.0 + (s * s * u + s)
    half = q >> 1
    first = (half + 127 << 23).to(tl.float32, bitcast=True)
    second = (q - half + 127 << 23).to(tl.float32, bitcast=True)
    result = u * first * second
    return result

@triton.jit
def _reciprocal_guarded_domain(d):
    # Caller supplies 1 + exp([-16,16]), finite and >= 1.
    bits=d.to(tl.int32, bitcast=True)
    safe=bits
    mantissa_bits=(safe&0x007fffff)|0x3f800000
    mantissa=mantissa_bits.to(tl.float32,bitcast=True)
    # The bit seed and Newton refinement strategy also used by llama.cpp's
    # hvx-inverse.h; arithmetic here is explicit IEEE FP32 Triton, not QFloat.
    inverse=(0x7eeeebb3-mantissa_bits).to(tl.float32,bitcast=True)
    for i in tl.static_range(3):
        inverse=inverse*(2.0-mantissa*inverse)
    inverse=tl.where(mantissa_bits==0x3f800000,1.0,inverse)
    exponent=(safe>>23)-127
    # d is in [1, 1 + exp(16)], so the rescaled reciprocal stays normal.
    scale=((127-exponent)<<23).to(tl.float32,bitcast=True)
    result=inverse*scale
    return result


@triton.jit
def _up_value(U,S,W,row,indices):
    accum=tl.load(U+row*3072+indices).to(tl.float32)
    scale=tl.load(S+row*3072+indices)
    weight=tl.load(W+indices)
    return (scale*accum)*weight

@triton.jit
def _domain_violation(x,up):
    # Positive FP32 bit patterns are monotone. For bits b, the
    # violation max(min(L-b,b),b-H) is <=0 exactly for b==0 or
    # L<=b<=H. Integer min/max avoids packed-predicate round trips.
    # Gate: zero or [2^-64,16]; up: zero or [2^-32,2^32].
    # Masked bits are in [0,INT_MAX], so these differences cannot overflow.
    # NaN/Inf are outside this domain.
    xb=x.to(tl.int32,bitcast=True)&0x7fffffff
    ub=up.to(tl.int32,bitcast=True)&0x7fffffff
    xbad=tl.maximum(tl.minimum(0x1f800000-xb,xb),xb-0x41800000)
    ubad=tl.maximum(tl.minimum(0x2f800000-ub,ub),ub-0x4f800000)
    return xbad, tl.maximum(xbad,ubad)

@triton.jit
def _guarded_product(x,up):
    xbad,flag=_domain_violation(x,up)
    goodx=xbad<=0
    safe_x=tl.where(goodx,x,0.0)
    z=(x*_reciprocal_guarded_domain(1.0+_exp_guarded_domain(-safe_x)))*up
    return z, flag

@triton.jit
def silu_product(G,U,S,W,Y,rows,BLOCK:tl.constexpr=32,MODE:tl.constexpr=1):
    lane=tl.arange(0,BLOCK)
    for row in range(tl.program_id(0),rows,4):
        if MODE==0:
            for col in range(0,3072,BLOCK):
                x=tl.load(G+row*3072+col+lane)
                up=_up_value(U,S,W,row,col+lane)
                z=tl.div_rn(x,1.0+_exp_compat(-x))*up
                tl.store(Y+row*3072+col+lane,z)
        else:
            # Interleave two independent 32-lane products before storing.
            # This exposes independent work without constructing v64 predicates.
            # Finite absolute-value bit patterns preserve the max ordering;
            # Rejected blocks are repaired before the quantizer consumes them.
            vmax=tl.full((BLOCK,),0,tl.int32)
            bad=tl.full((BLOCK,),0,tl.int32)
            for col in range(0,3072,2*BLOCK):
                x0=tl.load(G+row*3072+col+lane)
                up0=_up_value(U,S,W,row,col+lane)
                x1=tl.load(G+row*3072+col+BLOCK+lane)
                up1=_up_value(U,S,W,row,col+BLOCK+lane)
                z0,b0=_guarded_product(x0,up0)
                z1,b1=_guarded_product(x1,up1)
                tl.store(Y+row*3072+col+lane,z0)
                tl.store(Y+row*3072+col+BLOCK+lane,z1)
                bad=tl.maximum(bad,tl.maximum(b0,b1))
                block_max=tl.maximum(z0.to(tl.int32,bitcast=True)&0x7fffffff,
                                     z1.to(tl.int32,bitcast=True)&0x7fffffff)
                vmax=tl.maximum(vmax,block_max)
            # Only the scalar peak crosses the repair branch; each vector
            # accumulator stays within its own loop.
            peak_bits=tl.max(vmax,0)
            if tl.max(bad,0)>0:
                # Repair only blocks outside the approximation's admitted domain.
                # Other blocks keep the same relative-error guarantee; exact
                # blocks have zero approximation error. Rebuild the mixed peak.
                repairmax=tl.full((BLOCK,),0,tl.int32)
                for col in range(0,3072,BLOCK):
                    x=tl.load(G+row*3072+col+lane)
                    up=_up_value(U,S,W,row,col+lane)
                    _,violation=_domain_violation(x,up)
                    if tl.max(violation,0)>0:
                        z=tl.div_rn(x,1.0+_exp_compat(-x))*up
                        tl.store(Y+row*3072+col+lane,z)
                    repaired=tl.load(Y+row*3072+col+lane)
                    repairmax=tl.maximum(repairmax,repaired.to(tl.int32,bitcast=True)&0x7fffffff)
                peak_bits=tl.max(repairmax,0)
            if peak_bits>=0x7f800000:
                # Nonfinite output cannot use the finite quantizer proof.
                # Preserve the original complete strict row and NaN behavior.
                for col in range(0,3072,BLOCK):
                    x=tl.load(G+row*3072+col+lane)
                    up=_up_value(U,S,W,row,col+lane)
                    z=tl.div_rn(x,1.0+_exp_compat(-x))*up
                    tl.store(Y+row*3072+col+lane,z)
            else:
                peak=peak_bits.to(tl.float32,bitcast=True)
                lowpeak=peak*(1.0-0.0000152587890625)
                exactmax=tl.full((BLOCK,),0,tl.int32)
                # Strictly recompute every block containing a possible max.
                for col in range(0,3072,BLOCK):
                    z=tl.load(Y+row*3072+col+lane)
                    if tl.max(tl.abs(z).to(tl.int32,bitcast=True),0).to(tl.float32,bitcast=True)*(1.0+0.0000152587890625)>=lowpeak:
                        x=tl.load(G+row*3072+col+lane)
                        up=_up_value(U,S,W,row,col+lane)
                        z=tl.div_rn(x,1.0+_exp_compat(-x))*up
                        tl.store(Y+row*3072+col+lane,z)
                    repaired=tl.load(Y+row*3072+col+lane)
                    exactmax=tl.maximum(exactmax,repaired.to(tl.int32,bitcast=True)&0x7fffffff)
                # Match the model quantizer's FP32(1e-5) floor, not machine epsilon.
                scale=tl.maximum(tl.div_rn(tl.max(exactmax,0).to(tl.float32,bitcast=True),127.0),0.00001)
                inv=tl.div_rn(1.0,scale)
                # Preserve strict round-to-nearest-even INT8 decisions.
                for col in range(0,3072,BLOCK):
                    z=tl.load(Y+row*3072+col+lane)
                    q=tl.abs(z*inv)
                    halfway=q.to(tl.int32).to(tl.float32)+0.5
                    distance=tl.abs(q-halfway)-q*0.000030517578125
                    bits=distance.to(tl.int32,bitcast=True)
                    key=bits^((bits>>31)&0x7fffffff)
                    if tl.min(key,0)<=0x37800000:
                        x=tl.load(G+row*3072+col+lane)
                        up=_up_value(U,S,W,row,col+lane)
                        z=tl.div_rn(x,1.0+_exp_compat(-x))*up
                        tl.store(Y+row*3072+col+lane,z)
