"""q1 attention with FP32 persistent KV and packed HVX QFloat arithmetic.

QK uses a vector tree reduction; PV shares each row across two GQA heads.
This changes rounding and does not promise bitwise equality with strict decode.
Batch 1, 16 Q heads, 8 KV heads, dimension 128, effective KV 1..1024.
No padding mask: the adapter validates that every occupied key is visible.
"""
