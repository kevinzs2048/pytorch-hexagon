@triton.jit
def _reduce_qf(a):
    for shift in tl.static_range(0,5):
        b=tl.gather(a,(tl.arange(0,32)+(16 >> shift)) % 32,axis=0)
        a=_qf_add(a,b)
    bits=_to_sf(a)
    return tl.sum(tl.gather(bits,tl.full((1,),0,tl.int32),axis=0),0).to(tl.float32,bitcast=True)

@triton.jit
def attention_decode(Q, K, V, Out, Scratch, query_length, kv_length, q_head_stride, q_token_stride, k_head_stride, k_token_stride, v_head_stride, v_token_stride, BLOCK_N: tl.constexpr=64, APPROX_EXP: tl.constexpr=False, HEADS_PER_PROGRAM: tl.constexpr=4, SOFTMAX_BLOCK: tl.constexpr=8):
    tl.static_assert(HEADS_PER_PROGRAM == 4)
    tl.static_assert(not APPROX_EXP)
    tl.static_assert(SOFTMAX_BLOCK == 8 or SOFTMAX_BLOCK == 32)
    first_head = tl.program_id(1) * HEADS_PER_PROGRAM
    # Retain the established SLEEF exponent and denominator evaluation.
    softmax_lane = tl.arange(0, SOFTMAX_BLOCK)
    pack_cols = tl.arange(0, 32)
    for head in range(first_head, first_head + HEADS_PER_PROGRAM, 2):
        kv_head = head // 2
        # QK: reuse query vectors and shared K across the two GQA heads.
        q00 = tl.load(Q + head * q_head_stride + pack_cols).to(tl.int32, bitcast=True)
        q01 = tl.load(Q + head * q_head_stride + 32 + pack_cols).to(tl.int32, bitcast=True)
        q02 = tl.load(Q + head * q_head_stride + 64 + pack_cols).to(tl.int32, bitcast=True)
        q03 = tl.load(Q + head * q_head_stride + 96 + pack_cols).to(tl.int32, bitcast=True)
        q10 = tl.load(Q + (head + 1) * q_head_stride + pack_cols).to(tl.int32, bitcast=True)
        q11 = tl.load(Q + (head + 1) * q_head_stride + 32 + pack_cols).to(tl.int32, bitcast=True)
        q12 = tl.load(Q + (head + 1) * q_head_stride + 64 + pack_cols).to(tl.int32, bitcast=True)
        q13 = tl.load(Q + (head + 1) * q_head_stride + 96 + pack_cols).to(tl.int32, bitcast=True)
        for position in range(0, kv_length):
            k0 = tl.load(K + kv_head * k_head_stride + position * k_token_stride + pack_cols).to(tl.float32).to(tl.int32, bitcast=True)
            k1 = tl.load(K + kv_head * k_head_stride + position * k_token_stride + 32 + pack_cols).to(tl.float32).to(tl.int32, bitcast=True)
            k2 = tl.load(K + kv_head * k_head_stride + position * k_token_stride + 64 + pack_cols).to(tl.float32).to(tl.int32, bitcast=True)
            k3 = tl.load(K + kv_head * k_head_stride + position * k_token_stride + 96 + pack_cols).to(tl.float32).to(tl.int32, bitcast=True)
            a0 = _qf_add(_qf_mul_sf(q00,k0), _qf_mul_sf(q01,k1))
            b0 = _qf_add(_qf_mul_sf(q02,k2), _qf_mul_sf(q03,k3))
            a1 = _qf_add(_qf_mul_sf(q10,k0), _qf_mul_sf(q11,k1))
            b1 = _qf_add(_qf_mul_sf(q12,k2), _qf_mul_sf(q13,k3))
            score0 = _reduce_qf(_qf_add(a0,b0))
            score1 = _reduce_qf(_qf_add(a1,b1))
            tl.store(Scratch + head * 1024 + position, score0 * 0.08838834764831845)
            tl.store(Scratch + (head + 1) * 1024 + position, score1 * 0.08838834764831845)
        for current_head in range(head, head + 2):
            maximum = -float('inf')
            for col in range(0, kv_length):
                score = tl.load(Scratch + current_head * 1024 + col)
                maximum = tl.where((score > maximum) | (score != score), score, maximum)
            for start in range(0, kv_length, SOFTMAX_BLOCK):
                positions = start + softmax_lane
                scores = tl.load(Scratch + current_head * 1024 + positions, positions < kv_length, other=-float('inf'))
                probability = _exp_compat(scores - maximum)
                tl.store(Scratch + current_head * 1024 + positions, probability, positions < kv_length)
            if kv_length < 4:
                total = 0.0
                for col in range(0, kv_length):
                    total = total + tl.load(Scratch + current_head * 1024 + col)
            else:
                sums = (0.0, 0.0, 0.0, 0.0)
                for col in range(0, kv_length // 4 * 4, 4):
                    for i in tl.static_range(0, 4):
                        value = sums[i] + tl.load(Scratch + current_head * 1024 + col + i)
                        sums = sums[:i] + (value,) + sums[i + 1:]
                for i in tl.static_range(0, 4):
                    if kv_length // 4 * 4 + i < kv_length:
                        value = sums[i] + tl.load(Scratch + current_head * 1024 + kv_length // 4 * 4 + i)
                        sums = sums[:i] + (value,) + sums[i + 1:]
                total = sums[0] + sums[2] + (sums[1] + sums[3])
            inverse = 1.0 / total
            for start in range(0, kv_length, SOFTMAX_BLOCK):
                positions = start + softmax_lane
                probability = tl.load(Scratch + current_head * 1024 + positions, positions < kv_length, other=0) * inverse
                tl.store(Scratch + current_head * 1024 + positions, probability, positions < kv_length)
        # Traverse each V row once and update all 128 features of both heads.
        accum = (tl.full((32,),0,tl.int32),tl.full((32,),0,tl.int32),
                 tl.full((32,),0,tl.int32),tl.full((32,),0,tl.int32),
                 tl.full((32,),0,tl.int32),tl.full((32,),0,tl.int32),
                 tl.full((32,),0,tl.int32),tl.full((32,),0,tl.int32))
        for row in range(0,kv_length):
            p0=tl.full((32,),0,tl.float32)+tl.load(Scratch+head*1024+row)
            p1=tl.full((32,),0,tl.float32)+tl.load(Scratch+(head+1)*1024+row)
            for i in tl.static_range(0,4):
                v=tl.load(V+kv_head*v_head_stride+row*v_token_stride+i*32+pack_cols).to(tl.float32).to(tl.int32,bitcast=True)
                x=_qf_add(accum[i],_qf_mul_sf(p0.to(tl.int32,bitcast=True),v))
                accum=accum[:i]+(x,)+accum[i+1:]
                y=_qf_add(accum[4+i],_qf_mul_sf(p1.to(tl.int32,bitcast=True),v))
                accum=accum[:4+i]+(y,)+accum[5+i:]
        for i in tl.static_range(0,4):
            tl.store(Out+head*128+i*32+pack_cols,_to_sf(accum[i]).to(tl.float32,bitcast=True))
            tl.store(Out+(head+1)*128+i*32+pack_cols,_to_sf(accum[4+i]).to(tl.float32,bitcast=True))
