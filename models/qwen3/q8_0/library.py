"""libqwen_q8_0_weights.so and the qwen_q8_0_weight(id) table.

The packed tiles of weights.build() become one read-only constant library with
the recipe of the shared libqwen_dynamic_kv_prefill_const_N.so (ld.lld
separate loadable segments, then split_constant_load_segments: <= 256 MiB per
LOAD); the table source is linked into the code library (model.so).
"""
import json
import os
import subprocess
from pathlib import Path

from .weights import sha

SONAME = "libqwen_q8_0_weights.so"


def table_source(rows):
    src = ["// Generated by models/qwen3/q8_0/library.py: Q8_0 projection id -> packed tiles.",
           "#include <cstdint>", 'extern "C" {']
    src += [f"extern const uint8_t qwen_q8_0_w{r['id']}[];" for r in rows]
    src += ["}", "namespace {", "struct Entry { const uint8_t *data; uint32_t n, k; };", "const Entry table[] = {"]
    src += [f"  {{qwen_q8_0_w{r['id']}, {r['n']}, {r['k']}}}," for r in rows]
    src += ["};", "}  // namespace", 'extern "C" const uint8_t *qwen_q8_0_weight(int64_t id, uint32_t *n, uint32_t *k) {',
            f"  if (id < 0 || id >= {len(rows)}) return nullptr;",
            "  *n = table[id].n;", "  *k = table[id].k;", "  return table[id].data;", "}"]
    return "\n".join(src) + "\n"


def build(weights, out, hexagon_tools, lld, python, repo_root, env=None):
    """weights: directory of weights.build(); writes the library, its proof, the table and build.json."""
    weights, out = Path(weights), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    rows = json.loads((weights / "weights.json").read_text())["projections"]
    if [r["id"] for r in rows] != list(range(len(rows))):
        raise ValueError("Q8_0 ids must be 0..N-1 in order")
    for r in rows:
        blob = weights / f"{r['id']}.q8"
        if blob.stat().st_size != r["packed_bytes"] or sha(blob) != r["packed_sha256"]:
            raise ValueError(f"Q8_0 tiles changed: {blob}")
    asm = ["// Generated by models/qwen3/q8_0/library.py"]
    for r in rows:
        name = f"qwen_q8_0_w{r['id']}"
        blob = (weights / f"{r['id']}.q8").resolve()
        asm += [f'.section .rodata.{name},"a",@progbits', ".p2align 11", f".globl {name}", f".type {name},@object",
                f".size {name},{r['packed_bytes']}", f"{name}:", f'.incbin "{blob}"']
    (out / "q8_0_weights.S").write_text("\n".join(asm) + "\n")
    env = dict(os.environ if env is None else env, TMPDIR=str(out))
    tools = Path(hexagon_tools) / "bin"
    run = lambda argv: subprocess.run([str(a) for a in argv], env=env, check=True)
    run([tools / "hexagon-clang", "-mv73", "-fPIC", "-G0", "-c", out / "q8_0_weights.S", "-o", out / "q8_0_weights.o"])
    lib = out / SONAME
    unsplit = out / (SONAME + ".unsplit")
    run([tools / "hexagon-clang++", "-O3", "-mv73", "-mhvx", f"--ld-path={lld}", "-Wl,-z,separate-loadable-segments",
         "-shared", "-fPIC", "-G0", "-mlong-calls", "-nostdlib++", out / "q8_0_weights.o", f"-Wl,-soname,{SONAME}",
         "-o", unsplit])
    proof = out / (SONAME + ".proof.json")
    for f in (lib, proof):
        f.unlink(missing_ok=True)  # the splitter writes fresh files only
    subprocess.run([str(python), "-m", "hexagon_runtime.split_constant_load_segments", "--input", str(unsplit),
                    "--output", str(lib), "--proof", str(proof), "--expected-sha256", sha(unsplit)],
                   env=env, check=True, cwd=str(repo_root))
    (out / "q8_0_weight_table.cpp").write_text(table_source(rows))
    info = dict(library=str(lib), library_sha256=sha(lib), bytes=lib.stat().st_size, unsplit_sha256=sha(unsplit),
                proof_sha256=sha(proof), table=str(out / "q8_0_weight_table.cpp"),
                table_sha256=sha(out / "q8_0_weight_table.cpp"), weights_json_sha256=sha(weights / "weights.json"),
                count=len(rows))
    unsplit.unlink()
    (out / "q8_0_weights.o").unlink()
    (out / "build.json").write_text(json.dumps(info, indent=1))
    return info
